export function getSeedLocationsForCampaign(
  campaignId: number,
  role: ViewerRole,
): readonly LocationInspectorDetailVm[] {
  const isGm = role === 'gm';
  const raw = campaignId === 1 ? SEED_LOCATIONS_C1 : [];
  return raw
    .filter((l) => isGm || (l.visibility !== 'gm' && l.discoveryStatus !== 'undiscovered'))
    .map((l) =>
      isGm
        ? l
        : {
            ...l,
            childMapId: l.childMapId === 'map-mountain-prison' ? null : l.childMapId,
            relatedEntities: l.relatedEntities.filter((r) => r.visibility !== 'gm'),
            historyEvents: l.historyEvents.filter((h) => h.visibility !== 'gm'),
            secrets: [],
          },
    );
}
